/* Testes do servidor da Central. Uso: node testes/teste-servidor.js */
const {criarSimulador} = require("./simulador-apps-script");
const assert = require("assert");
const sim = criarSimulador({CRIADOR_EMAILS:"criador@teste.com", PIMENTA:"pimenta-de-teste-com-mais-de-vinte-caracteres"});
const c = d => sim.chamar(d);
const ultimoCodigo = email => { const m = sim.emails.filter(e => e.to === email && /código/.test(e.subject)).pop(); return m && m.subject.match(/(\d{6})/)[1]; };
let n = 0; const ok = (cond, msg) => { assert.ok(cond, msg); n++; console.log("  ✓ " + msg); };

console.log("Cadastro e confirmação");
let r = c({acao:"cadastrar", app:"prospectarion", nome:"Maria Silva", email:"Maria@Teste.com", senha:"curta", consentimento:"v1"});
ok(!r.ok && r.erro === "senha", "recusa senha fraca");
r = c({acao:"cadastrar", app:"prospectarion", nome:"Maria", email:"maria@teste.com", senha:"senha1234", consentimento:"v1"});
ok(!r.ok, "exige nome e sobrenome");
r = c({acao:"cadastrar", app:"prospectarion", nome:"Maria Silva", email:"maria@teste.com", senha:"senha1234"});
ok(!r.ok, "exige consentimento LGPD");
r = c({acao:"cadastrar", app:"prospectarion", nome:"Maria Silva", email:"Maria@Teste.com", senha:"senha1234", consentimento:"termos v1"});
ok(r.ok && r.confirmar, "cadastra e pede confirmação");
const cod1 = ultimoCodigo("maria@teste.com");
ok(/^\d{6}$/.test(cod1), "envia código de 6 dígitos por e-mail");
r = c({acao:"entrar", email:"maria@teste.com", senha:"senha1234", app:"prospectarion"});
ok(!r.ok && r.erro === "nao_confirmado", "não entra sem confirmar e-mail");
r = c({acao:"confirmar", email:"maria@teste.com", codigo:"000000"});
ok(!r.ok && r.erro === "codigo", "recusa código errado");
r = c({acao:"confirmar", email:"maria@teste.com", codigo:ultimoCodigo("maria@teste.com"), app:"prospectarion"});
ok(r.ok && r.token && r.licenca.status === "teste" && r.licenca.liberado, "confirma, abre sessão e libera teste do Prospectarion");
r = c({acao:"cadastrar", app:"prospectarion", nome:"Outra Pessoa", email:"maria@teste.com", senha:"outra1234", consentimento:"v1"});
ok(!r.ok && r.erro === "email_existe", "não deixa cadastrar e-mail já confirmado");

console.log("Login, licença e bloqueio");
r = c({acao:"entrar", email:"maria@teste.com", senha:"errada123"});
ok(!r.ok && r.erro === "login", "senha errada não entra");
for(let i = 0; i < 4; i++) c({acao:"entrar", email:"maria@teste.com", senha:"errada123"});
r = c({acao:"entrar", email:"maria@teste.com", senha:"senha1234"});
ok(!r.ok && r.erro === "bloqueio", "bloqueia após 5 erros, mesmo com a senha certa");

console.log("Esqueci a senha");
r = c({acao:"esqueciSenha", email:"ninguem@teste.com"});
ok(r.ok && /Se o e-mail/.test(r.mensagem), "não revela e-mail inexistente");
r = c({acao:"esqueciSenha", email:"maria@teste.com"});
const codSenha = ultimoCodigo("maria@teste.com");
r = c({acao:"redefinirSenha", email:"maria@teste.com", codigo:codSenha, novaSenha:"nova"});
ok(!r.ok && r.erro === "senha", "nova senha fraca recusada");
r = c({acao:"redefinirSenha", email:"maria@teste.com", codigo:codSenha, novaSenha:"novaSenha99", app:"prospectarion"});
ok(r.ok && r.token, "redefine a senha com o código e entra (desbloqueia)");
const tokenMaria = r.token;
ok(sim.emails.some(e => e.to === "maria@teste.com" && /senha foi alterada/.test(e.subject)), "avisa por e-mail que a senha mudou");
r = c({acao:"entrar", email:"maria@teste.com", senha:"senha1234"});
ok(!r.ok, "senha antiga deixa de funcionar");
r = c({acao:"acesso", token:tokenMaria, app:"pro-imobiliaria"});
ok(r.ok && !r.liberado && r.licenca.status === "analise", "PRO IMOBILIÁRIA começa em análise");
r = c({acao:"acesso", token:tokenMaria, app:"mesa-de-editais"});
ok(r.ok && !r.liberado && r.licenca.status === "lista", "Mesa de Editais começa na lista de lançamento");

console.log("Painel do Criador");
r = c({acao:"adminContas", token:tokenMaria});
ok(!r.ok && r.erro === "proibido", "cliente não acessa o painel");
c({acao:"cadastrar", app:"prospectarion", nome:"Anderson Alves", email:"criador@teste.com", senha:"criador123", consentimento:"v1"});
r = c({acao:"confirmar", email:"criador@teste.com", codigo:ultimoCodigo("criador@teste.com"), app:"prospectarion"});
const tokenCriador = r.token;
ok(r.conta.criador && r.licenca.plano === "criador", "criador entra com plano criador");
r = c({acao:"adminLicenca", token:tokenCriador, email:"maria@teste.com", app:"pro-imobiliaria", status:"ativo", plano:"mensal", vencimento:"2099-12-31", avisar:true});
ok(r.ok && r.licenca.liberado, "criador libera o app para a cliente");
ok(sim.emails.some(e => e.to === "maria@teste.com" && /liberado/.test(e.subject)), "cliente recebe e-mail com o link do app");
r = c({acao:"acesso", token:tokenMaria, app:"pro-imobiliaria"});
ok(r.liberado, "app abre para a cliente");
r = c({acao:"adminLicenca", token:tokenCriador, email:"maria@teste.com", app:"prospectarion", status:"ativo", vencimento:"2020-01-01"});
r = c({acao:"acesso", token:tokenMaria, app:"prospectarion"});
ok(!r.liberado && r.licenca.status === "vencido", "licença vencida bloqueia o app");
r = c({acao:"meusApps", token:tokenMaria});
ok(r.ok && r.apps.length === 3, "Meus apps lista os 3 apps da cliente");
r = c({acao:"chamado", token:tokenMaria, app:"prospectarion", tipo:"suporte", mensagem:"=HYPERLINK(\"x\") não consigo exportar"});
ok(r.ok, "cliente abre chamado");
ok(String(sim.abas.Chamados.rows[1][4]).startsWith("'"), "texto com fórmula é neutralizado na planilha");
r = c({acao:"adminConta", token:tokenCriador, email:"maria@teste.com", status:"bloqueado"});
r = c({acao:"sessao", token:tokenMaria});
ok(!r.ok, "conta bloqueada perde a sessão na hora");
r = c({acao:"adminResumo", token:tokenCriador});
ok(r.ok && r.contas === 2 && r.chamadosAbertos === 1, "resumo do painel confere");

console.log("Segurança da planilha");
const contas = sim.abas.Contas.rows;
ok(!JSON.stringify(contas).includes("novaSenha99") && !JSON.stringify(contas).includes("criador123"), "nenhuma senha em texto na planilha");
ok(!JSON.stringify(sim.abas.Codigos.rows).match(/\b\d{6}\b/), "códigos guardados só como hash");
ok(!JSON.stringify(sim.abas.Sessoes.rows).includes(tokenCriador), "tokens de sessão guardados só como hash");
r = c({acao:"catalogo"});
ok(r.ok && r.apps.length === 5, "catálogo público com 5 apps");
console.log("\n" + n + " verificações OK");
